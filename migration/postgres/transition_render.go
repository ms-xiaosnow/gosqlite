func (m *transitionModel) render(ctx context.Context) (TransitionBundle, error) {
	b := TransitionBundle{Report: m.r, Artifacts: []TransitionArtifact{}}
	total := 0
	add := func(name, kind, tx, content string) error {
		if err := ctx.Err(); err != nil {
			return err
		}
		if len(content) > m.max-total {
			return fmt.Errorf("transition: generated byte limit")
		}
		total += len(content)
		b.Artifacts = append(b.Artifacts, TransitionArtifact{name, kind, tx, sqlHash(content), content})
		return nil
	}
	jsonText := func(v any) (string, error) { p, e := json.MarshalIndent(v, "", "  "); return string(p) + "\n", e }
	report, err := jsonText(m.r)
	if err != nil {
		return TransitionBundle{}, err
	}
	if err = add("report.json", "report", "none", report); err != nil {
		return TransitionBundle{}, err
	}
	// Definitions are evidence-only JSON, never pasted into a SQL phase.
	inventory, err := jsonText(struct {
		CatalogSHA256    string          `json:"catalog_sha256"`
		DependencySHA256 string          `json:"dependency_sha256"`
		Snapshot         CatalogSnapshot `json:"snapshot"`
	}{m.r.CatalogSHA256, m.r.DependencySHA256, m.c})
	if err != nil {
		return TransitionBundle{}, err
	}
	if err = add("inventory.json", "evidence_only", "none", inventory); err != nil {
		return TransitionBundle{}, err
	}
	var mdreport bytes.Buffer
	if err = RenderMarkdown(&mdreport, m.r.Inspection); err != nil {
		return TransitionBundle{}, err
	}
	fmt.Fprintf(&mdreport, "\n## Transition gates\n\nPlan: %s\n\nStatus: %s; PostgreSQL execution has not occurred.\n", m.r.PlanSHA256, m.r.Status)
	for _, g := range m.r.Gates {
		fmt.Fprintf(&mdreport, "- %s / %s: %s\n", md(g.Code), md(g.State), md(g.Requirement))
	}
	if err = add("report.md", "report", "none", mdreport.String()); err != nil {
		return TransitionBundle{}, err
	}
	if err = add("README.md", "review_instructions", "none", m.readme()); err != nil {
		return TransitionBundle{}, err
	}
	if err = add("00-preflight.sql", "read_only_reference", "independent_read_only", m.preflight()); err != nil {
		return TransitionBundle{}, err
	}
	tx := "shared_offline_transaction"
	if m.o.Mode == TransitionBatches {
		tx = "separate_transactions"
	}
	phases := []struct{ name, tx, sql string }{
		{"10-extension-transition.sql", tx, m.extensionSQL()},
		{"20-shadow-copy.sql", tx, m.copySQL()},
		{"30-batch.sql", tx, m.batchSQL()},
		{"40-indexes.sql", tx, m.indexSQL()},
		{"50-verify.sql", tx, m.verifySQL()},
		{"60-application-cutover.sql", tx, m.applicationSQL()},
		{"70-rollback.sql", tx, m.rollbackSQL()},
	}
	if m.o.ConcurrentIndexes {
		phases[3].tx = "outside_explicit_transaction"
	}
	for _, p := range phases {
		body := p.sql
		if m.r.Status == "blocked" && p.name != "70-rollback.sql" {
			body = "BLOCKED: proposed statements withheld. Resolve blocked report gates and regenerate.\n"
		}
		if err = add(p.name, "review_only_sql", p.tx, reviewSQL(body)); err != nil {
			return TransitionBundle{}, err
		}
	}
	sort.Slice(b.Artifacts, func(i, j int) bool { return b.Artifacts[i].Name < b.Artifacts[j].Name })
	type file struct {
		Name, Kind, Transaction, SHA256 string
		Bytes                           int
	}
	files := make([]file, 0, len(b.Artifacts))
	for _, a := range b.Artifacts {
		files = append(files, file{a.Name, a.Kind, a.Transaction, a.SHA256, len(a.Content)})
	}
	manifest, err := jsonText(struct {
		FormatVersion int    `json:"format_version"`
		PlanSHA256    string `json:"plan_sha256"`
		CatalogSHA256 string `json:"catalog_sha256"`
		Status        string `json:"status"`
		MutationMode  string `json:"mutation_mode"`
		Files         []file `json:"files"`
	}{1, m.r.PlanSHA256, m.r.CatalogSHA256, m.r.Status, "commented_review_only_never_executed", files})
	if err != nil {
		return TransitionBundle{}, err
	}
	if err = add("manifest.json", "manifest", "none", manifest); err != nil {
		return TransitionBundle{}, err
	}
	sort.Slice(b.Artifacts, func(i, j int) bool { return b.Artifacts[i].Name < b.Artifacts[j].Name })
	return b, nil
}

func reviewSQL(body string) string {
	// No user definition enters body; still handle both SQL line terminators so
	// no future text source can escape a comment through a bare carriage return.
	body = strings.ReplaceAll(strings.ReplaceAll(body, "\r\n", "\n"), "\r", "\n")
	return "-- REVIEW ONLY. NOT AN EXECUTABLE MIGRATION. All approvals remain unresolved.\n-- Remove no comment prefixes until an operator has reviewed each phase and gate.\n-- " + strings.ReplaceAll(strings.TrimSuffix(body, "\n"), "\n", "\n-- ") + "\n"
}

func (m *transitionModel) tableSQL() string { return objectKey(m.table.Schema, m.table.Name) }
func (m *transitionModel) vectorType() string {
	return fmt.Sprintf("%s(%d)", objectKey(m.o.VectorSchema, "vector"), m.o.Dimensions)
}
func (m *transitionModel) stateSQL() string { return objectKey(m.o.StateSchema, m.o.StateTable) }
func (m *transitionModel) expression(alias string) string {
	if alias != "" {
		alias += "."
	}
	if m.o.Approach == TypedCopyShadow {
		return alias + quoteIdent(m.o.ShadowColumn)
	}
	return "(" + alias + quoteIdent(m.column.Name) + "::" + m.vectorType() + ")"
}

func (m *transitionModel) readme() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Offline PostgreSQL transition review\n\nStatus: %s. Plan `%s`. No PostgreSQL command has been run.\n\nApproach: `%s`; transaction mode: `%s`.\n\n", m.r.Status, m.r.PlanSHA256, m.o.Approach, m.o.Mode)
	b.WriteString("Only 00-preflight.sql contains active read-only SQL. It is an operator-reviewed diagnostic reference, not an automatic step. Every later SQL file is fully line-commented, including its SELECT/BEGIN/COMMIT statements. No flag or supplied approval changes that. The JSON renderer does not run or write artifacts.\n\nRead report.json, report.md and inventory.json first. Any blocked gate suppresses all proposed migration statements. Unresolved gates are mandatory human approvals and external evidence, never automatically satisfied by this generator. A synthetic catalog is not proof of a server. Manifest hashes identify bytes, not authenticity. The manifest lists all other artifacts, not itself.\n\n## Required order\n\n1. Verify source backups and old-extension reinstall/restore availability. Pause application writes and DDL, including primary-key changes, and capture legacy exact-query/business baselines before removing embedding. Audit every dependency and arbitrary application/dynamic SQL.\n2. Review and run the bounded-time read-only preflight. Array profiling is an exhaustive potentially expensive read. Recollect a complete catalog; compare its canonical_json_v1 hash and dependency hash with this plan. Diagnostics alone are not the full fingerprint. Schema drift, incomplete visibility, bad rows or unknown target availability means stop and regenerate.\n3. Obtain every report approval. Review privileges, extension installation policy, disk/WAL capacity, lock cost and maintenance duration. Tables and extensions need appropriate ownership as well as ordinary DML privileges.\n4. Review phase 10: exact legacy index drops, extension RESTRICT removal, target creation and exact post-install capability inspection. Both extensions own database-wide hnsw; schema isolation does not solve this collision. Do not use CASCADE, rename access methods or modify catalogs.\n5. Review copy, batch and index phases. Keep source real[] arrays intact. Normal CREATE INDEX may share a transaction; concurrent creation must be outside every explicit transaction and is incompatible with the single-transaction mode.\n6. Inspect valid/ready index flags and exact definitions, counts, PKs, NULL alignment, float32 values, norms, exact-distance/business fixtures, ANN recall and real staging query plans before cutover. This package has not performed these PostgreSQL checks.\n7. Approve coordinated application SQL, vector-text binding, settings, column choice, NULL/zero policy, tie order and filter rollout. An old Manhattan <~> must become dense <+>; modern bit <~> is Hamming. See the separate AST converter for supported source-span conversions, never global replacement.\n8. Preserve original arrays and export for the rollback window. Future writes must keep arrays current. No source rename, source drop, table drop, cleanup or generic dual-write trigger is generated.\n\n")
	if m.o.Mode == TransitionSingle {
		b.WriteString("## One offline transaction\n\nPhases 10, 20, 40, 50 and the commit part of 60 share one connection and one still-open transaction. Phase 10 takes ACCESS EXCLUSIVE on the selected table. Review statements, resolve post-install/data checks and prepare application deployment before committing. Do not execute a COMMIT merely because the file exists. Phase 30 is unused. Normal ROLLBACK before COMMIT reverses that transaction's DDL/data changes; it does not undo external application deployment. A large transaction retains locks and WAL/disk costs throughout; sub-batching inside it would not release them.\n\n")
	} else {
		b.WriteString("## Multiple transactions\n\nPhase 10 commits the extension transition separately; phase 20 commits shadow/state setup. A later ROLLBACK cannot restore those committed steps. External write quiescence must hold between commits. Phase 30 is a single-worker repeatable keyset batch with plan-bound persistent state locked and advanced in the same transaction as the copied rows. Read progress before retrying after an ambiguous client response; never infer completion from printed output. The NULL initial cursor includes MinInt64. Source NULL vectors still count as processed rows. No OFFSET, SKIP LOCKED, target-IS-NULL progress filter or in-memory-only cursor is used. Completion needs an empty batch and exact expected source count. A zero-row progress result, or empty batch without complete=true, means stop and inspect. Parallel workers, state adoption and interrupted execution qualification are unsupported.\n\n")
	}
	if m.o.Approach == RetainArrayCast {
		b.WriteString("## Retained-array approach\n\nNo shadow or backfill is created. New indexes use an explicit vector(n) cast expression and queries must use that same expression and verified operator schema. Removing embedding still removes old distance functions/operators and ANN service; retained data alone does not preserve that service. Every new array write must remain castable.\n\n")
	} else {
		b.WriteString("## Typed-copy approach\n\nThe supported typed copy adds one nullable vector(n) shadow column to the existing table. It is not the historical full-table-copy recipe: defaults, constraints, grants, dependent bindings and table replacement are not recreated. Source NULL remains shadow NULL. Application switch uses the explicit shadow name; no column rename is generated.\n\n")
	}
	b.WriteString("## Rollback boundaries\n\nBefore the single transaction commits, database ROLLBACK is transactional. After any migration commit, stopping shadow reads only abandons the data-copy workflow; it cannot restore the dropped old extension or old indexes. After application cutover, stop writers and reconcile any newer data with retained arrays before switching readers. Restoring old ANN may require a separate database/branch restore or reviewed reverse migration, available old binaries and removal/reconciliation of vector-owned dependencies. hnsw collides in the reverse direction too. No automatic post-cutover rollback is promised. Cleanup requires a separate approval and plan.\n\n## Pinned evidence\n\nSource: " + SourceProfile + ". Target: " + TargetProfile + ". Current Neon page retrieved 2026-10-10; requested migration chapter is absent. Historical official chapter is a separate source: " + HistoricalNeonURL + ". Neither current Neon availability nor a live PostgreSQL execution is claimed.\n")
	return b.String()
}
